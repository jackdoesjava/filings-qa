"""Parses every filing the questions use into page texts and chunks, then checks
that FinanceBench's evidence_page_num points at the page we think it does.

Writes data/processed/pages.jsonl, data/processed/chunks.jsonl and
reports/page_alignment.md. Takes under a minute."""

import re
from collections import Counter, defaultdict
from statistics import median

from fqa.data import (DOC_PAGE_OFFSET, PAGE_OFFSET, PDFS, PROCESSED, QUESTIONS, REPORTS, read_jsonl,
                      write_jsonl)
from fqa.ingest import build_chunks, char_overlap, offset_scores, read_pdf_pages, word_overlap

OFFSETS = (-1, 0, 1)
MATCH = 0.8  # on char_overlap


def fmt(offset):
    return f"{offset:+d}" if offset else "0"


def squash(text):
    return re.sub(r"[^a-z0-9]", "", text.lower())


raw = read_jsonl(QUESTIONS)
docs = sorted({r["doc_name"] for r in raw})
pages_by_doc = {doc: read_pdf_pages(PDFS / f"{doc}.pdf") for doc in docs}

write_jsonl(PROCESSED / "pages.jsonl", ({"doc": doc, "page": i, "text": text}
                                        for doc, pages in pages_by_doc.items() for i, text in enumerate(pages)))
chunks = build_chunks(pages_by_doc)
write_jsonl(PROCESSED / "chunks.jsonl", chunks)

n_pages = sum(len(pages) for pages in pages_by_doc.values())
empty = {(doc, i) for doc, pages in pages_by_doc.items() for i, text in enumerate(pages) if not text}
print(f"{len(docs)} filings, {n_pages} pages ({len(empty)} with no text), {len(chunks)} chunks")

# FinanceBench's text of each evidence page against our page at evidence_page_num + offset
items = []
for r in raw:
    for e in r["evidence"]:
        doc, page, text = e["doc_name"], e["evidence_page_num"], e["evidence_text_full_page"]
        char = offset_scores(text, pages_by_doc[doc], page, char_overlap, OFFSETS)
        word = offset_scores(text, pages_by_doc[doc], page, word_overlap, OFFSETS)
        ok = [o for o in OFFSETS if char[o] >= MATCH]
        items.append({"id": r["financebench_id"], "doc": doc, "page": page, "text": text, "char": char,
                      "word": word, "match": max(ok, key=lambda o: (char[o], -abs(o))) if ok else None})

matched = [it for it in items if it["match"] is not None]
unmatched = [it for it in items if it["match"] is None]
assert matched, "no evidence page matches at any offset: are these the right PDFs?"
best = Counter(it["match"] for it in matched).most_common(1)[0][0]
by_doc = defaultdict(Counter)
for it in matched:
    by_doc[it["doc"]][it["match"]] += 1
own = {doc: c.most_common(1)[0][0] for doc, c in sorted(by_doc.items()) if c.most_common(1)[0][0] != best}
agrees = PAGE_OFFSET == best and DOC_PAGE_OFFSET == own

n = len(items)
n_distinct = len({(it["doc"], it["page"]) for it in items})
lines = [
    "# Page alignment",
    "",
    "Generated by scripts/02_ingest.py.",
    "",
    "FinanceBench gives each evidence item a page number (`evidence_page_num`) and the text of that page as they "
    "extracted it (`evidence_text_full_page`). Retrieval is scored against those page numbers, so before using them "
    "I compared every evidence page with our pymupdf parse at `evidence_page_num + offset` for offsets -1, 0 and +1: "
    f"{n} evidence items from {len(raw)} questions, {n_distinct} distinct pages in {len(docs)} filings.",
    "",
    "Overlap is a weighted Jaccard over word counts (lowercase letters and digits), and the same over character "
    "5-grams once spaces and punctuation are removed. The second one decides: a page matches if it scores at least "
    f"{MATCH}. On some financial statement pages FinanceBench's text has the spaces between words dropped "
    "(\"Cashandcashequivalents\"), and there the numbers are about the only words the two texts share.",
    "",
    "| offset | evidence items matching | median 5-gram overlap | median word overlap |",
    "|--:|--:|--:|--:|",
]
for o in OFFSETS:
    k = sum(it["char"][o] >= MATCH for it in items)
    lines.append(f"| {fmt(o)} | {k} of {n} ({k / n:.1%}) | {median(it['char'][o] for it in items):.2f} | "
                 f"{median(it['word'][o] for it in items):.2f} |")

lines += [
    "",
    f"- Chosen offset: {fmt(best)}. " + ("No filing matches better at another offset." if not own else
                                         "Filings that match better at another offset: "
                                         + ", ".join(f"{d} ({fmt(o)})" for d, o in own.items()) + "."),
    f"- `load_questions` in `fqa/data.py` uses offset {fmt(PAGE_OFFSET)}"
    + (f" with per-filing offsets {DOC_PAGE_OFFSET}" if DOC_PAGE_OFFSET else " for every filing")
    + (", which agrees with this check." if agrees else
       ", which DISAGREES with this check: update PAGE_OFFSET and DOC_PAGE_OFFSET there."),
]

lo = min(it["char"][it["match"]] for it in matched)
nb = max((it["char"][o], it["doc"], it["page"] + o) for it in matched for o in OFFSETS if o != it["match"])
same = sum(squash(it["text"]) == squash(pages_by_doc[it["doc"]][it["page"] + it["match"]]) for it in matched)
lines.append(f"- For {same} of the {len(matched)} matched items FinanceBench's text is identical to ours once spaces "
             f"and punctuation are removed, and the lowest 5-gram overlap on a matching page is {lo:.2f}. The best "
             f"score on a neighbouring page is {nb[0]:.2f} ({nb[1]} page {nb[2]}), so any threshold between the "
             "two gives the same answer.")

lo_w = min(it["word"][it["match"]] for it in matched)
nb_w = max((it["word"][o], it["doc"], it["page"] + o) for it in matched for o in OFFSETS if o != it["match"])
weak = {}
for it in sorted(matched, key=lambda it: it["word"][it["match"]]):
    if it["word"][it["match"]] < nb_w[0]:
        weak.setdefault((it["doc"], it["page"]), it)
if weak:
    lines.append(f"- Word overlap alone would not have settled it: on the matching page it goes as low as {lo_w:.2f}, "
                 f"while a neighbouring page reaches {nb_w[0]:.2f} ({nb_w[1]} page {nb_w[2]}). The {len(weak)} "
                 "matching pages below that on words, each with the longest run of letters in FinanceBench's "
                 "text for it:")
    for (doc, page), it in weak.items():
        longest = max(re.findall(r"[A-Za-z]+", it["text"]), key=len, default="")
        lines.append(f"  - {doc} page {page}: word overlap {it['word'][it['match']]:.2f}, \"{longest}\"")

if unmatched:
    lines.append(f"- Evidence items that match at no offset ({len(unmatched)} of {n}), with the best-matching page "
                 "anywhere in the filing:")
    for it in unmatched:
        pages = pages_by_doc[it["doc"]]
        anywhere = max(range(len(pages)), key=lambda i: char_overlap(it["text"], pages[i]))
        lines.append(f"  - {it['doc']} page {it['page']} ({it['id']}): best at -1/0/+1 is "
                     f"{max(it['char'].values()):.2f}, best anywhere is page {anywhere} at "
                     f"{char_overlap(it['text'], pages[anywhere]):.2f}"
                     + ("; FinanceBench has no text for it" if not it["text"].strip() else "")
                     + ("; our page has no text" if (it["doc"], it["page"]) in empty else ""))
else:
    lines.append("- Evidence items that match at no offset: none.")

if empty:
    gold = {(it["doc"], it["page"] + own.get(it["doc"], best)) for it in items}
    by_filing = Counter(doc for doc, _ in empty).most_common()
    where = ", ".join(f"{doc} {k}" for doc, k in by_filing[:3])
    if len(by_filing) > 3:
        where += f", {len(by_filing) - 3} other filings with at most {by_filing[3][1]} each"
    lines.append(f"- {len(empty)} of our {n_pages:,} pages have no extractable text ({where}); "
                 f"{len(gold & empty)} of them are evidence pages.")

REPORTS.mkdir(parents=True, exist_ok=True)
(REPORTS / "page_alignment.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"page alignment: {len(matched)} of {n} evidence items match, best offset {fmt(best)}, "
      f"{len(own)} filings with their own offset; see reports/page_alignment.md")
if not agrees:
    print("WARNING: fqa/data.py page offsets disagree with the alignment check")
