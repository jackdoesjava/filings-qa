"""Grades every answer file in results/answers/.

A question whose gold answer is a single number (62 of the 150) is graded by
comparing numbers. The rest go to a judge model (qwen2.5:7b by default) through
Ollama, one call at a time. Verdicts are cached in results/judgements.jsonl,
keyed by question, config, model and a hash of the answer, so a re-run only
judges answers it has not seen. The judge is never told which config or model
wrote an answer.

By default the judge also marks the numerically graded answers, to see how far
it agrees with the automatic grade where the truth is known; --no-validate
makes no new calls for those (about 62 per answer file) but still uses any
already cached. --no-judge makes no model calls at all, and anything without a
cached verdict is left ungraded and out of the accuracy figures.

Writes results/scores.jsonl and reports/accuracy.md. Works on whatever answer
files exist, including partial ones from a smoke test."""

import argparse
import json
import sys
import time

import pandas as pd

from fqa.data import REPORTS, RESULTS, load_questions
from fqa.score import (GOLD_FIXES, JUDGE, NO_RETRIEVAL, cohen_kappa, gold_answer, grade_row, is_numeric_gold,
                       load_judgements)
from fqa.stats import bootstrap_ci, grouped_bootstrap_ci, paired_diff_ci

ANSWERS = RESULTS / "answers"
JUDGEMENTS = RESULTS / "judgements.jsonl"
CONFIGS = ["closed_book", "rag_bm25", "rag_dense", "rag_hybrid", "agent", "oracle"]
BASELINES = ["closed_book", "rag_bm25"]
QTYPES = ["metrics-generated", "domain-relevant", "novel-generated"]
FAILURES = ["unit error", "retrieval miss", "refusal", "other"]
HARDWARE = "a 4GB GTX 1050 Ti, through Ollama's Vulkan backend"


def read_answers(path):
    rows = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                pass  # a blank line, or one that 05_answer.py is still writing
    return rows


def in_order(configs):
    known = [c for c in CONFIGS if c in set(configs)]
    return known + sorted(set(configs) - set(known))


def pct_ci(x, questions=None):
    # pass the question ids when the same question can come up more than once
    mean, lo, hi = bootstrap_ci(x) if questions is None else grouped_bootstrap_ci(x, questions)
    return f"{100 * mean:.1f} [{100 * lo:.1f}, {100 * hi:.1f}]"


def share(x):
    return f"{100 * x.mean():.1f} (n={len(x)})" if len(x) else ""


def md(rows, floatfmt=".1f"):
    df = pd.DataFrame(rows)
    return df.astype(object).where(df.notna(), "").to_markdown(index=False, floatfmt=floatfmt)


def grade_all(files, questions, args):
    cache = load_judgements(JUDGEMENTS)
    scores = {}
    for path in files:
        config, _, model = path.stem.partition("__")
        rows = read_answers(path)
        print(f"{path.name}: {len(rows)} answers", flush=True)
        t0, judged, unknown = time.time(), 0, 0
        for i, row in enumerate(rows, 1):
            q = questions.get(row.get("id"))
            if q is None:
                unknown += 1
                continue
            row = {"config": config, "model": model} | row  # the file name only fills gaps
            n = len(cache)
            s = grade_row(q, row, cache, JUDGEMENTS, args.judge, call_judge=not args.no_judge,
                          validate=not args.no_validate)
            scores[s["config"], s["model"], s["id"]] = s
            if len(cache) > n:
                judged += 1
                print(f"  [{i}/{len(rows)}] {q['id']} judged {s['judge_verdict']}", flush=True)
        print(f"  {judged} newly judged in {time.time() - t0:.0f}s"
              + (f", {unknown} with an unknown id skipped" if unknown else ""), flush=True)
    return list(scores.values())


def report(df, questions, n_files, judge_model):
    graded = df[df["correct"].notna()].copy()
    graded["correct"] = graded["correct"].astype(float)
    models = sorted(df["model"].unique())
    pairs = [(m, c) for m in models for c in in_order(df.loc[df["model"] == m, "config"])]
    numeric = [q for q in questions.values() if is_numeric_gold(gold_answer(q), q["question"])]
    fixes = "; ".join(f"{i.removeprefix('financebench_id_')}: {questions[i]['answer']} is graded as {gold}"
                      for i, gold in GOLD_FIXES.items() if i in questions)
    per_type = pd.Series([q["qtype"] for q in numeric]).value_counts()
    type_total = pd.Series([q["qtype"] for q in questions.values()]).value_counts()
    qtypes = [t for t in QTYPES if t in type_total] + sorted(set(type_total.index) - set(QTYPES))

    def cell(m, c, frame=None):
        frame = df if frame is None else frame
        return frame[(frame["model"] == m) & (frame["config"] == c)]

    out = [
        "# Answer accuracy\n",
        f"Generated by scripts/06_score.py from {n_files} answer files in results/answers/.\n",
        f"{len(numeric)} of the {len(questions)} questions have a gold answer that is a single number ("
        + ", ".join(f"{per_type.get(t, 0)} {t}" for t in qtypes) + "). Those are graded automatically: correct "
        "if a number on the reply's `Answer:` line is within 1% of the gold, or rounds to it (some golds are given "
        "to one significant figure), with 25% and 0.25 counted as equal. A money figure off by a factor of a "
        "thousand, million or billion is counted wrong and labelled a unit error. For capex and dividends, a "
        "minus sign copied from the cash flow statement does not count against the answer. The rest are graded by "
        f"{judge_model} with a strict rubric. It sees the question, the gold answer and its justification and "
        "the reply, never which config or model wrote it. Intervals are 95% percentile bootstraps over questions "
        "(2,000 resamples).\n",
    ]
    if fixes:
        out.append(f"Gold answers that disagree with the filing are corrected before grading ({fixes}; the "
                   "reasons are in GOLD_FIXES in fqa/score.py).\n")
    ungraded = int(df["correct"].isna().sum())
    if ungraded:
        out.append(f"{ungraded} answers have no verdict yet (the judge was not run on them) and are left out of "
                   "every figure below.\n")

    rows = []
    for m, c in pairs:
        g, n = cell(m, c, graded), len(cell(m, c))
        rows.append({"model": m, "config": c, "answered": n, "graded": len(g),
                     "accuracy % [95% CI]": pct_ci(g["correct"]) if len(g) else "",
                     "numeric questions": share(g.loc[g["method"] == "numeric", "correct"]),
                     "judged questions": share(g.loc[g["method"] == "judge", "correct"])})
    out += ["## Accuracy\n", md(rows) + "\n"]

    rows = []
    for m in models:
        sub, done = graded[graded["model"] == m], set()
        for base in BASELINES:
            b = sub.loc[sub["config"] == base].set_index("id")["correct"]
            for c in in_order(sub["config"]):
                if b.empty or c == base or frozenset((c, base)) in done:
                    continue
                done.add(frozenset((c, base)))
                a = sub.loc[sub["config"] == c].set_index("id")["correct"]
                ids = a.index.intersection(b.index)
                if len(ids):
                    d, lo, hi = paired_diff_ci(a[ids].to_numpy(), b[ids].to_numpy())
                    rows.append({"model": m, "comparison": f"{c} - {base}", "questions": len(ids),
                                 "difference, points [95% CI]": f"{100 * d:+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}]"})
    if rows:
        out += ["## Paired differences\n",
                "Same model, same questions, each config against closed_book and rag_bm25. The interval comes "
                "from resampling the questions once and scoring both configs on the same resample.\n",
                md(rows) + "\n"]

    rows = []
    for m, c in pairs:
        g = cell(m, c, graded)
        row = {"model": m, "config": c}
        for t in qtypes:
            x = g.loc[g["qtype"] == t, "correct"]
            row[t] = (pct_ci(x) + ("" if len(x) == type_total[t] else f" (n={len(x)})")) if len(x) else ""
        rows.append(row)
    out += ["## By question type\n",
            "Accuracy % [95% CI]. " + ", ".join(f"{type_total[t]} {t}" for t in qtypes)
            + " questions in all; n is shown where fewer were graded.\n", md(rows) + "\n"]

    rows = []
    for m, c in pairs:
        a = cell(m, c)
        rows.append({"model": m, "config": c, "questions": len(a),
                     "model calls / q": a["steps"].mean(), "tool calls / q": a["tool_calls"].mean(),
                     "prompt tokens / q": a["prompt_tokens"].mean(), "cached / q": a["cached_tokens"].mean(),
                     "output tokens / q": a["output_tokens"].mean(),
                     "prompt tokens/s": ((a["prompt_tokens"] - a["cached_tokens"]).sum() / a["prompt_s"].sum()
                                         if a["prompt_s"].sum() else None),
                     "output tokens/s": a["output_tokens"].sum() / a["gen_s"].sum() if a["gen_s"].sum() else None,
                     "latency s/q, mean": a["total_s"].mean(), "latency s/q, median": a["total_s"].median()})
    out += ["## Cost and speed\n",
            "Per question, summed over every model call it took. Cached is the part of the prompt Ollama "
            "reused from the call before instead of processing it again (the system prompt, and the agent's "
            "earlier turns), so prompt tokens/s counts only the tokens it did process. Tokens per second are "
            f"totals over the file. One model at a time on {HARDWARE}.\n", md(rows) + "\n"]

    rows = []
    for m, c in pairs:
        a, g = cell(m, c), cell(m, c, graded)
        wrong = g[g["correct"] == 0]
        counts = wrong["failure"].value_counts()
        row = {"model": m, "config": c, "wrong": len(wrong), **{f: int(counts.get(f, 0)) for f in FAILURES}}
        hits = a["retrieval_hit"].dropna()
        row["gold page shown %"] = 100 * hits.astype(float).mean() if len(hits) else None
        if c in NO_RETRIEVAL:
            row["retrieval miss"] = "-"
        rows.append(row)
    out += ["## Why answers were wrong\n",
            "Each wrong answer gets the first label that applies. Unit error: the right figure in the wrong scale. "
            "Retrieval miss: no chunk the model was shown came from a gold evidence page (does not apply to "
            "closed_book and oracle). Refusal: no answer given. Other: a wrong figure or conclusion from what it "
            "was shown. The last column is the share of all answers where a gold page was shown.\n",
            md(rows) + "\n"]

    v = graded[(graded["method"] == "numeric") & graded["judge_verdict"].notna()]
    out.append("## Judge against the automatic grade\n")
    if len(v):
        rows = []
        for name, part in [("all", v)] + [(c, v[v["config"] == c]) for c in in_order(v["config"])]:
            auto, judge = part["correct"] == 1, part["judge_verdict"] == "correct"
            rows.append({"answers": name, "n": len(part), "agreement %": 100 * (auto == judge).mean(),
                         "Cohen's kappa": cohen_kappa(auto, judge),
                         "both correct": int((auto & judge).sum()), "both wrong": int((~auto & ~judge).sum()),
                         "judge accepts, grader rejects": int((~auto & judge).sum()),
                         "judge rejects, grader accepts": int((auto & ~judge).sum())})
        auto, judge = v["correct"] == 1, v["judge_verdict"] == "correct"
        units = v[v["verdict"] == "unit_error"]
        accepted = int((units["judge_verdict"] == "correct").sum())
        out.append(
            f"The judge also marked {len(v)} numerically graded answers, where the automatic grade is the "
            f"reference. It agrees on {pct_ci((auto == judge).astype(float), v['id'])}% of them (Cohen's kappa "
            f"{cohen_kappa(auto, judge):.2f}, correct versus not)."
            + (f" Of the {len(units)} unit errors it accepted {accepted}." if len(units) else "")
            + " Agreement here is the best evidence there is for trusting its verdicts on the other questions, "
            "which are harder to judge. The same question comes up once per config and model, so the interval "
            "resamples questions, each with all of its answers. Kappa is 0 when either of the two gives every "
            "answer the same mark, and blank when both mark every answer correct or both mark every answer "
            "wrong.\n")
        out.append(md(rows, floatfmt=("", "", ".1f", ".2f")) + "\n")
    else:
        out.append("Not run: the judge has not marked any numerically graded answers yet (run 06_score.py "
                   "without --no-validate or --no-judge).\n")
    return "\n".join(out)


def main():
    p = argparse.ArgumentParser(description="Grade every answer file in results/answers/.")
    p.add_argument("--judge", default=JUDGE, help=f"Ollama model used as the judge (default {JUDGE})")
    p.add_argument("--no-judge", action="store_true", help="make no model calls; use cached verdicts only")
    p.add_argument("--no-validate", action="store_true",
                   help="no new judge calls for numerically graded answers (cached ones are still used)")
    args = p.parse_args()

    files = sorted(ANSWERS.glob("*.jsonl"))
    if not files:
        print(f"no answer files in {ANSWERS}; run scripts/05_answer.py first")
        return
    questions = {q["id"]: q for q in load_questions()}
    scores = grade_all(files, questions, args)
    if not scores:
        print("nothing to grade: no answer matched a question id")
        return

    RESULTS.mkdir(parents=True, exist_ok=True)
    with open(RESULTS / "scores.jsonl", "w", encoding="utf-8", newline="\n") as fh:
        for s in scores:
            fh.write(json.dumps(s) + "\n")
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "accuracy.md").write_text(report(pd.DataFrame(scores), questions, len(files), args.judge),
                                         encoding="utf-8", newline="\n")
    print(f"wrote {RESULTS / 'scores.jsonl'} and {REPORTS / 'accuracy.md'}")


if __name__ == "__main__":
    sys.stdout.reconfigure(errors="replace")
    main()
